const number = new Intl.NumberFormat('ru', { useGrouping: false, maximumFractionDigits: 2 }).format;
const plural = new Intl.PluralRules('ru');
function counted(value: number, one: string, few: string, many: string) {
  const form = plural.select(value);
  return `${number(value)} ${form === 'one' ? one : form === 'few' ? few : many}`;
}

